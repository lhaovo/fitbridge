import { readFileSync } from 'node:fs';
import FitParser from 'fit-file-parser';
const buf = readFileSync(process.argv[2]);
const parser = new FitParser({ mode: 'both', includeUnmappedMessages: true });
const p = await parser.parseAsync(buf);
console.log('=== events 前 8 个 ===');
for (const e of (p.events||[]).slice(0,8)) console.log('  ', JSON.stringify({t:e.timestamp, event:e.event, event_type:e.event_type, event_group:e.event_group, data:e.data, timer_time:e.timer_time, sport:e.sport}));
console.log('=== events 类型分布 ===');
const dist={}; for(const e of (p.events||[])) dist[e.event+'/'+e.event_type]=(dist[e.event+'/'+e.event_type]||0)+1;
console.log(' ', JSON.stringify(dist));
console.log('=== laps 前后各 2 个 ===');
const L=p.laps||[];
for (const l of [...L.slice(0,2), ...L.slice(-2)]) console.log('  ', JSON.stringify({st:l.start_time, el:l.total_elapsed_time, dist:l.total_distance, avg:l.avg_speed, hr:l.avg_heart_rate, pw:l.avg_power, trig:l.lap_trigger, sp:l.sport, idx:l.message_index}));
console.log('=== device_info ===');
for (const d of (p.device_infos||[])) console.log('  ', JSON.stringify({m:d.manufacturer,p:d.product,s:d.serial_number,idx:d.device_index,desc:d.descriptor,type:d.device_type,sw:d.software_version}));
console.log('=== sports ===', JSON.stringify(p.sports));
console.log('=== file_ids ===', JSON.stringify(p.file_ids));
